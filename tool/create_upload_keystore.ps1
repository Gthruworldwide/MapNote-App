# Creates the Android upload keystore and its `key.properties`.
#
# The keystore itself is a secret: it is written to `android/app/` and is
# ignored by git (`android/.gitignore` lists `key.properties`, `**/*.keystore`
# and `**/*.jks`). This script is the versioned, reproducible part -- it lets a
# developer recreate the key on a new machine without ever committing it.
#
# `android/key.properties` is what the Gradle build reads; it is written here
# with the same values, so the build picks the key up automatically.
#
# IMPORTANT: the upload key must be backed up outside the repository. If it is
# lost, Google Play can no longer accept updates for the package under the
# same signing identity.
#
# Usage:
#   powershell -File tool/create_upload_keystore.ps1
#   powershell -File tool/create_upload_keystore.ps1 -Password "my-secret"
#   powershell -File tool/create_upload_keystore.ps1 -Alias upload -Validity 10000

param(
  [string]$Password = "",
  [string]$Alias = "upload",
  [int]$Validity = 10000,
  [string]$StoreFile = "upload-keystore.jks",
  [switch]$Force
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path $PSScriptRoot -Parent
$androidDir = Join-Path $repoRoot "android"
$appDir = Join-Path $androidDir "app"
$keystorePath = Join-Path $appDir $StoreFile
$keyPropertiesPath = Join-Path $androidDir "key.properties"

# --- Locate keytool -------------------------------------------------------
# Prefer the JDK Flutter itself uses, so the key is generated by the same
# toolchain that will later sign the bundle.
$keytool = $null
$flutterJdkDir = (flutter config --list 2>$null | Select-String -Pattern "jdk-dir:\s*(.+)$")
if ($flutterJdkDir) {
  $candidate = Join-Path $flutterJdkDir.Matches[0].Groups[1].Value.Trim() "bin\keytool.exe"
  if (Test-Path $candidate) { $keytool = $candidate }
}
if (-not $keytool -and $env:JAVA_HOME) {
  $candidate = Join-Path $env:JAVA_HOME "bin\keytool.exe"
  if (Test-Path $candidate) { $keytool = $candidate }
}
if (-not $keytool) {
  $command = Get-Command keytool -ErrorAction SilentlyContinue
  if ($command) { $keytool = $command.Source }
}
if (-not $keytool) {
  throw "keytool not found. Install a JDK (17+) or set JAVA_HOME, or run: flutter config --jdk-dir <path>"
}

# --- Password -------------------------------------------------------------
if ([string]::IsNullOrWhiteSpace($Password)) {
  # 128 bits of entropy, hex-encoded so the value needs no escaping in a
  # Java `.properties` file and no quoting in a shell.
  $bytes = New-Object byte[] 16
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $rng.GetBytes($bytes)
  $Password = -join ($bytes | ForEach-Object { $_.ToString("x2") })
}

if ((Test-Path $keystorePath) -and -not $Force) {
  throw "keystore already exists: $keystorePath (pass -Force to replace it, and back the old one up first)"
}

# --- Create the key -------------------------------------------------------
& $keytool -genkeypair -v `
  -keystore $keystorePath `
  -storetype JKS `
  -alias $Alias `
  -keyalg RSA `
  -keysize 2048 `
  -validity $Validity `
  -storepass $Password `
  -keypass $Password `
  -dname "CN=MapNote Upload, OU=Engineering, O=MapNote, L=Cairo, C=EG"
if ($LASTEXITCODE -ne 0) { throw "keytool failed with exit code $LASTEXITCODE" }

# --- Write key.properties -------------------------------------------------
# `storeFile` is resolved by the Gradle build relative to `android/app/`.
$properties = @(
  "storePassword=$Password",
  "keyPassword=$Password",
  "keyAlias=$Alias",
  "storeFile=$StoreFile"
)
Set-Content -Path $keyPropertiesPath -Value $properties -Encoding ASCII

Write-Host ""
Write-Host "Keystore : $keystorePath"
Write-Host "Alias    : $Alias"
Write-Host "Validity : $Validity days"
Write-Host "Properties: $keyPropertiesPath"
Write-Host ""
Write-Host "Back the keystore up somewhere safe and outside this repository."
Write-Host "It is gitignored, but losing it locks you out of Play updates."
